import { z } from "zod";
import { idParamSchema, pageQuerySchema } from "@/contracts/common";
import {
  beneficiaryInputSchema,
  beneficiaryUpdateSchema,
  cancelPaymentSchema,
  nameEnquirySchema,
  paymentInputSchema,
  paymentListQuerySchema,
} from "@/contracts/payments";
import { getAccount, getBalance, getStatement, listAccounts } from "@/server/domain/accounts/service";
import {
  archiveBeneficiary,
  createBeneficiary,
  getBeneficiary,
  listBeneficiaries,
  nameEnquiry,
  updateBeneficiary,
} from "@/server/domain/payments/beneficiaries";
import {
  cancelPayment,
  createPayment,
  getPayment,
  listPayments,
  previewPayment,
  retryRelease,
  revisePayment,
  submitPayment,
  updatePaymentDraft,
} from "@/server/domain/payments/service";
import { command, query, type AnyOperation } from "../framework";

type IdParams = z.infer<typeof idParamSchema>;
type PaymentBody = z.infer<typeof paymentInputSchema>;

const statementQuery = z.strictObject({
  fromDate: z.iso.date().optional(),
  toDate: z.iso.date().optional(),
  view: z.enum(["intraday", "completed", "all"]).optional(),
  reference: z.string().trim().min(1).max(64).optional(),
  cursor: z.string().min(1).max(300).optional(),
  limit: z.coerce.number().int().min(1).max(100).optional(),
});

const beneficiaryListQuery = pageQuerySchema.extend({
  includeArchived: z.enum(["true", "false"]).optional(),
  search: z.string().trim().min(1).max(80).optional(),
});

const submitBody = z
  .strictObject({ acceptRolledExecution: z.boolean().optional(), acknowledgeCloseMatch: z.boolean().optional() })
  .optional();

export const accountOperations: AnyOperation[] = [
  query({
    id: "listAccounts",
    method: "GET",
    path: "/accounts",
    summary: "Assigned active accounts with balances",
    description: "Only accounts the caller holds a read grant on. A balance the core could not answer is reported as unavailable, never as zero.",
    tag: "Accounts",
    scope: "corporate",
    permission: "accounts.read",
    credentialScope: "accounts:read",
    handler: async ({ deps, ctx }) => ({ data: await listAccounts(deps, ctx) }),
  }),
  query<IdParams>({
    id: "getAccount",
    method: "GET",
    path: "/accounts/{id}",
    summary: "One assigned account",
    tag: "Accounts",
    scope: "corporate",
    permission: "accounts.read",
    credentialScope: "accounts:read",
    params: idParamSchema,
    handler: async ({ deps, ctx, params }) => ({ data: await getAccount(deps, ctx, params.id) }),
  }),
  query<IdParams>({
    id: "getAccountBalance",
    method: "GET",
    path: "/accounts/{id}/balance",
    summary: "Booked, available and held balance with as-of time",
    tag: "Accounts",
    scope: "corporate",
    permission: "accounts.read",
    credentialScope: "accounts:read",
    params: idParamSchema,
    handler: async ({ deps, ctx, params }) => ({ data: await getBalance(deps, ctx, params.id) }),
  }),
  query<IdParams, z.infer<typeof statementQuery>>({
    id: "getAccountStatement",
    method: "GET",
    path: "/accounts/{id}/statements",
    summary: "Paginated account activity",
    description: "Dates are bank business dates; at most 366 days per query. A payroll run is one consolidated line; per-employee postings are never returned.",
    tag: "Accounts",
    scope: "corporate",
    permission: "accounts.read",
    credentialScope: "accounts:read",
    params: idParamSchema,
    query: statementQuery,
    handler: async ({ deps, ctx, params, query: q }) => {
      const statement = await getStatement(deps, ctx, params.id, q);
      return { data: statement, page: { nextCursor: statement.nextCursor, hasMore: statement.nextCursor !== null } };
    },
  }),
];

