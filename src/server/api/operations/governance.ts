import { z } from "zod";
import { agreementProposalSchema, segmentSchema } from "@/contracts/agreement";
import { idParamSchema, reasonSchema } from "@/contracts/common";
import { listRailParameters, proposeRailParameter, railParameterProposalSchema } from "@/server/domain/agreements/rails";
import {
  getAgreementTemplate,
  getAgreementVersionReview,
  getBankAgreementOverview,
  getCorporateAgreement,
  listBankCorporates,
  proposeAgreementVersion,
  proposeRestore,
  suspendAgreement,
} from "@/server/domain/agreements/service";
import { getLimitsUsage } from "@/server/domain/agreements/usage";
import { command, query, type AnyOperation } from "../framework";

type IdParams = z.infer<typeof idParamSchema>;
const reasonBody = z.strictObject({ reason: reasonSchema });
const templateQuery = z.strictObject({ segment: segmentSchema.optional() });

export const agreementOperations: AnyOperation[] = [
  query({
    id: "getAgreement",
    method: "GET",
    path: "/agreement",
    summary: "Current signed modules, linked accounts, fees, limits, validity and history",
    description: "Read-only. A corporate session or API credential can never change an agreement.",
    tag: "Agreement",
    scope: "corporate",
    permission: "agreement.read",
    credentialScope: "agreements:read",
    handler: async ({ deps, ctx }) => ({ data: await getCorporateAgreement(deps, ctx) }),
  }),
  query({
    id: "getLimitsUsage",
    method: "GET",
    path: "/limits/usage",
    summary: "Policy windows and usage explanation (consumed, reserved, remaining)",
    tag: "Agreement",
    scope: "corporate",
    permission: "limits.read",
    credentialScope: "agreements:read",
    handler: async ({ deps, ctx }) => ({ data: await getLimitsUsage(deps, ctx) }),
  }),
];

export const bankGovernanceOperations: AnyOperation[] = [
  query({
    id: "listBankCorporates",
    method: "GET",
    path: "/bank/corporates",
    summary: "Corporates of the caller's bank with agreement status",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.corporates.read",
    handler: async ({ deps, ctx }) => ({ data: await listBankCorporates(deps, ctx) }),
  }),
  query<IdParams>({
    id: "listAgreementProposals",
    method: "GET",
    path: "/bank/corporates/{id}/agreement-proposals",
    summary: "Agreement revision history for one corporate",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.corporates.read",
    params: idParamSchema,
    handler: async ({ deps, ctx, params }) => ({ data: await getBankAgreementOverview(deps, ctx, params.id) }),
  }),
  query<IdParams, z.infer<typeof templateQuery>>({
    id: "getAgreementTemplate",
    method: "GET",
    path: "/bank/corporates/{id}/agreement-template",
    summary: "Segment demo template as a starting point for a proposal",
    description: "Synthetic test policy, not CBL or bank-approved limits and not a binding default.",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.agreement.propose",
    params: idParamSchema,
    query: templateQuery,
    handler: async ({ deps, ctx, params, query: q }) => ({ data: await getAgreementTemplate(deps, ctx, params.id, q.segment) }),
  }),
  command<IdParams, Record<string, never>, z.infer<typeof agreementProposalSchema>>({
    id: "proposeAgreementRevision",
    method: "POST",
    path: "/bank/corporates/{id}/agreement-proposals",
    summary: "Propose a full immutable agreement revision with simulated signature evidence",
    description:
      "Bank admin maker only. A different bank admin checker must approve it under /approvals. A module that this release does not deliver cannot be enabled (422 MODULE_UNAVAILABLE).",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.agreement.propose",
    params: idParamSchema,
    body: agreementProposalSchema,
    maxBodyBytes: 512 * 1024,
    successStatus: 201,
    execute: async ({ deps, ctx, params, body, newId }) => proposeAgreementVersion(deps, ctx, params.id, body, newId),
    render: async ({ deps, ctx }, ref) => getAgreementVersionReview(deps, ctx, ref.id),
  }),
  query<IdParams>({
    id: "getAgreementVersion",
    method: "GET",
    path: "/bank/agreement-versions/{id}",
    summary: "One revision with the field-level diff against the version it replaces",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.corporates.read",
    params: idParamSchema,
    handler: async ({ deps, ctx, params }) => ({ data: await getAgreementVersionReview(deps, ctx, params.id) }),
  }),
  command<IdParams, Record<string, never>, z.infer<typeof reasonBody>>({
    id: "suspendCorporateAgreement",
    method: "POST",
    path: "/bank/corporates/{id}/suspend",
    summary: "Emergency stop of a corporate's agreement (immediate, audited)",
    description: "Blocks new submissions and releases at once. Restoring requires an independently approved proposal.",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.corporate.suspend",
    params: idParamSchema,
    body: reasonBody,
    ifMatch: true,
    target: ({ params }) => ({ type: "corporate", id: params.id }),
    execute: async ({ deps, ctx, params, body, expectedVersion }) => suspendAgreement(deps, ctx, params.id, body.reason, expectedVersion),
    render: async ({ deps, ctx }, ref) => getBankAgreementOverview(deps, ctx, ref.id),
  }),
  command<IdParams, Record<string, never>, z.infer<typeof reasonBody>>({
    id: "proposeAgreementRestore",
    method: "POST",
    path: "/bank/corporates/{id}/restore-proposals",
    summary: "Propose restoring a suspended agreement (needs an independent checker)",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.agreement.propose",
    params: idParamSchema,
    body: reasonBody,
    successStatus: 201,
    target: ({ params }) => ({ type: "corporate", id: params.id }),
    execute: async ({ deps, ctx, params, body, newId }) => proposeRestore(deps, ctx, params.id, body.reason, newId),
    render: async ({ deps, ctx }, ref) => getBankAgreementOverview(deps, ctx, ref.id),
  }),
  query({
    id: "listRailParameterProposals",
    method: "GET",
    path: "/bank/rail-parameter-proposals",
    summary: "Rail ceilings, provenance, cut-offs, calendars and proposal history",
    description: "All values are configurable sandbox parameters; none is a confirmed CBL figure.",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.rail.read",
    handler: async ({ deps, ctx }) => ({ data: await listRailParameters(deps, ctx) }),
  }),
  command<Record<string, never>, Record<string, never>, z.infer<typeof railParameterProposalSchema>>({
    id: "proposeRailParameter",
    method: "POST",
    path: "/bank/rail-parameter-proposals",
    summary: "Propose a rail ceiling/cut-off change (approved through bank governance)",
    tag: "Bank governance",
    scope: "bank",
    permission: "bank.rail.propose",
    body: railParameterProposalSchema,
    successStatus: 201,
    execute: async ({ deps, ctx, body, newId }) => proposeRailParameter(deps, ctx, body, newId),
    render: async ({ deps, ctx }) => listRailParameters(deps, ctx),
  }),
];
